#!/usr/bin/env python3
"""fog_radial.py - the game's fog overlay with the distance along the eye's ray instead of the view's depth
(docs/re-xr-pipeline.md 137). Reads the two fog modules the layer dumped (SOMVR_XR_SPV_DUMP; IndirectX's translation of
fog_overlay.mat's pixel shaders: the opaque pass and the OIT pass) and writes somvr_fog_spv.h (the original's FNV-1a 64
and size, the patched words) for vklayer/somvr_fog_layer.c.

The fog's path length is a DXBC movc: sky ? the distance to the atmosphere's edge : rN.x, where rN = (z, x*z, y*z) is the
pixel's view-space position (z = the linear depth read from the depth buffer, x, y = the view ray at depth 1, v2.xy /
v1.w). rN.x is the depth along the view's axis: a pixel at the edge of a 100-degree view gets ~65 % of its true fog - the
fog a wall that turns with the head. The patch gives the movc length(rN.xyz) instead (the distance from the eye):

    %V = OpBitcast %uint %L            (%L = OpLoad %int (OpAccessChain %ptr %rN %c0) - the .x)
 -> %a = OpLoad %int4 %rN ; %b = OpBitcast %float4 %a ; %c = OpVectorShuffle %float3 %b %b 0 1 2 ;
    %d = OpExtInst %float %glsl Length %c ; %V = OpBitcast %uint %d

  fog_radial.py OUT.h MODULE.spv:CALLID [MODULE.spv:CALLID ...]
"""
import os
import struct
import sys


def _result_slots():
    import json
    g = json.load(open("/usr/include/spirv/unified1/spirv.core.grammar.json"))
    out = {}
    for i in g["instructions"]:
        ks = [o["kind"] for o in i.get("operands", [])]
        if ks[:2] == ["IdResultType", "IdResult"]:
            out[i["opcode"]] = 1
        elif ks[:1] == ["IdResult"]:
            out[i["opcode"]] = 0
    return out


RESULT = _result_slots()


def fnv(b):
    h = 1469598103934665603
    for c in b:
        h = ((h ^ c) * 1099511628211) & 0xffffffffffffffff
    return h


def parse(words):
    out, i = [], 5
    while i < len(words):
        wc, op = words[i] >> 16, words[i] & 0xffff
        out.append([op, list(words[i + 1:i + wc])])
        i += wc
    return out


def emit(header, insts):
    w = list(header)
    for op, a in insts:
        w.append(((len(a) + 1) << 16) | op)
        w += a
    return w


def patch(path, call):
    data = open(path, "rb").read()
    words = list(struct.unpack("<%dI" % (len(data) // 4), data))
    header, insts = words[:5], parse(words)
    defs = {}
    for k, (op, a) in enumerate(insts):
        r = RESULT.get(op)  # where the instruction's result id is (the SPIR-V grammar), None: it has none
        if r is not None and len(a) > r:
            defs[a[r]] = k
    tf = ti = tu = glsl = None
    vec = {}
    for op, a in insts:
        if op == 22 and a[1] == 32:
            tf = a[0]
        elif op == 21 and a[1] == 32:
            (ti, tu) = (a[0], tu) if a[2] == 1 else (ti, a[0])
        elif op == 11 and struct.pack("<%dI" % (len(a) - 1), *a[1:]).startswith(b"GLSL.std.450"):
            glsl = a[0]
    for op, a in insts:
        if op == 23:
            vec[(a[1], a[2])] = a[0]
    f3, f4 = vec.get((tf, 3)), vec.get((tf, 4))
    ci = defs.get(call)
    assert ci is not None and insts[ci][0] == 57, "no OpFunctionCall %%%d" % call
    stores = []
    k = ci - 1
    while k >= 0 and len(stores) < 3:
        if insts[k][0] == 62:
            stores.append(insts[k][1])
        k -= 1
    third = stores[0]  # the last store before the call = the third parameter
    vi = defs[third[1]]
    op, a = insts[vi]
    assert op == 124 and a[0] == tu, "the third argument is not OpBitcast %%uint"
    lop, la = insts[defs[a[2]]]
    assert lop == 61 and la[0] == ti, "the bitcast's value is not OpLoad %%int"
    aop, aa = insts[defs[la[2]]]
    assert aop == 65 and len(aa) == 4, "the load is not through OpAccessChain %%ptr %%reg %%idx"
    reg, idx = aa[2], aa[3]
    cop, ca = insts[defs[idx]]
    assert cop == 43 and ca[2] == 0, "the access chain's index is not the constant 0 (.x)"
    vop, va = insts[defs[reg]]
    assert vop == 59, "the register is not an OpVariable"
    pop, pa = insts[defs[va[0]]]
    assert pop == 32, "the register's type is not a pointer"
    i4 = pa[2]
    bound = header[3]
    n1, n2, n3, n4 = bound, bound + 1, bound + 2, bound + 3
    header[3] = bound + 4
    new = [[61, [i4, n1, reg]], [124, [f4, n2, n1]], [79, [f3, n3, n2, n2, 0, 1, 2]], [12, [tf, n4, glsl, 66, n3]]]
    insts[vi] = [124, [tu, a[1], n4]]
    insts[vi:vi] = new
    return data, emit(header, insts)


def main():
    out = sys.argv[1]
    lines = ["/* somvr_fog_spv.h - generated by shaders/fog_radial.py from the layer's dumps (SOMVR_XR_SPV_DUMP; docs/"
             "re-xr-pipeline.md 137): the game's fog overlay modules with the fog's path length the distance along the "
             "eye's ray (length of the view-space position) instead of its depth. Do not edit. */",
             "static const struct { uint64_t hash; uint32_t size; const char *what; uint32_t n; const uint32_t *words; } "
             "g_fog_spv[] = {"]
    arrays = []
    for k, arg in enumerate(sys.argv[2:]):
        path, call = arg.rsplit(":", 1)
        data, words = patch(path, int(call))
        name = "g_fog_spv_%d" % k
        what = os.path.basename(path)
        arrays.append("static const uint32_t %s[%d] = {\n%s\n};" % (
            name, len(words), ",\n".join(", ".join("0x%08x" % x for x in words[j:j + 8]) for j in range(0, len(words), 8))))
        lines.append("    {0x%016xULL, %d, \"%s (the movc %%%s's depth -> distance)\", %d, %s}," % (
            fnv(data), len(data), what, call, len(words), name))
        open(os.path.join(os.path.dirname(out) or ".", what.replace(".spv", ".radial.spv")), "wb").write(
            struct.pack("<%dI" % len(words), *words))
    lines.append("};")
    open(out, "w").write("\n".join(arrays) + "\n" + "\n".join(lines) + "\n")
    print("wrote", out)


main()
