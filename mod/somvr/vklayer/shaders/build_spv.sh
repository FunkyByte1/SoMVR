#!/usr/bin/env bash
# build_spv.sh - the VR hands' shaders (hands.vert, hands.frag; hands.frag again with WORLD_DEPTH) -> ../somvr_hands_spv.h (committed: the layer's build
# needs no shader compiler). glslangValidator (Khronos, Fedora's glslang package). --check: compare, write nothing.
set -euo pipefail
D=$(cd "$(dirname "$0")" && pwd)
OUT=$D/../somvr_hands_spv.h
command -v glslangValidator >/dev/null || { echo "spv: no glslangValidator: $OUT not checked"; exit 0; }
T=$(mktemp -d)
trap 'rm -rf -- "$T"' EXIT
glslangValidator -V --target-env vulkan1.0 --vn somvr_hands_vert_spv -o "$T/v.h" "$D/hands.vert" >/dev/null
glslangValidator -V --target-env vulkan1.0 --vn somvr_hands_frag_spv -o "$T/f.h" "$D/hands.frag" >/dev/null
glslangValidator -V --target-env vulkan1.0 -DWORLD_DEPTH --vn somvr_hands_world_frag_spv -o "$T/w.h" "$D/hands.frag" >/dev/null
{
    echo "/* somvr_hands_spv.h - GENERATED by shaders/build_spv.sh from shaders/hands.vert and shaders/hands.frag (twice)"
    echo " * (glslangValidator -V, Vulkan 1.0 SPIR-V); do not edit. */"
    echo "#ifndef SOMVR_HANDS_SPV_H"
    echo "#define SOMVR_HANDS_SPV_H"
    echo "#include <stdint.h>"
    grep -v '^\s*//\|#pragma once' "$T/v.h" | sed 's/^const uint32_t/static const uint32_t/'
    grep -v '^\s*//\|#pragma once' "$T/f.h" | sed 's/^const uint32_t/static const uint32_t/'
    grep -v '^\s*//\|#pragma once' "$T/w.h" | sed 's/^const uint32_t/static const uint32_t/'
    echo "#endif"
} > "$T/out.h"
if [ "${1:-}" = --check ]; then
    cmp -s "$T/out.h" "$OUT" && echo "spv: somvr_hands_spv.h up to date" || { echo "spv: somvr_hands_spv.h DIFFERS from the shaders"; exit 1; }
else
    cp "$T/out.h" "$OUT"
    echo "spv: wrote $OUT"
fi
