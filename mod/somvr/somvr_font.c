int somvr_font_index(int ch) {
    if (ch < SOMVR_FONT_FIRST || ch > SOMVR_FONT_LAST) ch = '?';
    return ch - SOMVR_FONT_FIRST;
}

/* one glyph's art into rows[16]: 0 = ok (8 columns of '.' or '#' per row, column 7 empty, inside rows 1..14) */
static int parse_art(const glyph_art *g, uint8_t rows[SOMVR_FONT_H]) {
    memset(rows, 0, SOMVR_FONT_H);
    const char *p = g->art;
    if (!*p) return 0;
    int y = g->top;
    if (y < 1) return -1;
    for (;; y++) {
        if (y > SOMVR_FONT_H - 2) return -1;
        uint8_t b = 0;
        for (int x = 0; x < SOMVR_FONT_W; x++, p++) {
            if (*p != '#' && *p != '.') return -1;
            if (*p == '#') {
                if (x == SOMVR_FONT_W - 1) return -1;
                b |= (uint8_t)(0x80u >> x);
            }
        }
        rows[y] = b;
        if (!*p) return 0;
        if (*p++ != '|') return -1;
    }
}

int somvr_font_init(somvr_font *f) {
    memset(f, 0, sizeof *f);
    int bad = 0;
    uint8_t seen[SOMVR_FONT_N] = {0};
    for (size_t i = 0; i < sizeof g_art / sizeof g_art[0]; i++) {
        const glyph_art *g = &g_art[i];
        int k = g->ch - SOMVR_FONT_FIRST;
        if (k < 0 || k >= SOMVR_FONT_N || seen[k]) {
            if (!bad) bad = g->ch ? g->ch : -1;
            continue;
        }
        seen[k] = 1;
        if (parse_art(g, f->row[k])) {
            memset(f->row[k], 0, sizeof f->row[k]);
            if (!bad) bad = g->ch;
        }
    }
    for (int k = 0; k < SOMVR_FONT_N && !bad; k++)
        if (!seen[k]) bad = k + SOMVR_FONT_FIRST; /* a code without art */
    f->ok = !bad;
    return bad;
}

uint8_t somvr_font_row(const somvr_font *f, int ch, int y) {
    return y >= 0 && y < SOMVR_FONT_H ? f->row[somvr_font_index(ch)][y] : 0;
}

int somvr_font_ink(const somvr_font *f, int ch, int box[4]) {
    int k = somvr_font_index(ch), any = 0;
    box[0] = box[1] = 99, box[2] = box[3] = -1;
    for (int y = 0; y < SOMVR_FONT_H; y++)
        for (int x = 0; x < SOMVR_FONT_W; x++)
            if (f->row[k][y] & (0x80u >> x)) {
                any = 1;
                if (x < box[0]) box[0] = x;
                if (y < box[1]) box[1] = y;
                if (x > box[2]) box[2] = x;
                if (y > box[3]) box[3] = y;
            }
    return any;
}

int somvr_font_text_w(const char *s, int scale) { return (int)strlen(s) * SOMVR_FONT_W * scale; }

int somvr_font_draw(const somvr_font *f, uint8_t *px, int w, int h, int x, int y, const char *s, int scale,
                    const uint8_t rgba[4], int bgra) {
    if (scale < 1) scale = 1;
    if (scale > 8) scale = 8;
    unsigned a = rgba[3];
    uint8_t c[4] = {(uint8_t)((rgba[bgra ? 2 : 0] * a + 127) / 255), (uint8_t)((rgba[1] * a + 127) / 255),
                    (uint8_t)((rgba[bgra ? 0 : 2] * a + 127) / 255), (uint8_t)a};
    for (; *s; s++, x += SOMVR_FONT_W * scale) {
        int k = somvr_font_index((unsigned char)*s);
        for (int gy = 0; gy < SOMVR_FONT_H; gy++) {
            uint8_t r = f->row[k][gy];
            if (!r) continue;
            for (int gx = 0; gx < SOMVR_FONT_W; gx++) {
                if (!(r & (0x80u >> gx))) continue;
                for (int sy = 0; sy < scale; sy++) {
                    int py = y + gy * scale + sy;
                    if (py < 0 || py >= h) continue;
                    for (int sx = 0; sx < scale; sx++) {
                        int pxx = x + gx * scale + sx;
                        if (pxx < 0 || pxx >= w) continue;
                        memcpy(px + 4 * ((size_t)py * (size_t)w + (size_t)pxx), c, 4);
                    }
                }
            }
        }
    }
    return x;
}
