#!/usr/bin/env python3
"""handmesh_gen.py - mod/somvr/assets/generic-hand/right.glb -> mod/somvr/somvr_handmesh.h (the VR hands' mesh,
docs/re-xr-pipeline.md 33). Plain python3 (no numpy): reads the GLB's JSON and binary chunks, checks the layout the C
side expects (25 joints in the WebXR order, rest transforms in model space, 4 weights a vertex) and writes C arrays.

    python3 -I scripts/handmesh_gen.py [GLB [OUT]]      (run from ShadowOfMordor/; --check: compare, write nothing)
"""
import hashlib
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GLB = os.path.join(HERE, '..', 'mod', 'somvr', 'assets', 'generic-hand', 'right.glb')
OUT = os.path.join(HERE, '..', 'mod', 'somvr', 'somvr_handmesh.h')
SHA = '291790c14f7f88a7f9bd35330c47392ed8e8d395ae6728f4bb7089f1bc1f2b96'
NAMES = ['wrist'] + ['%s-%s' % (f, j) for f, js in
                     (('thumb', ('metacarpal', 'phalanx-proximal', 'phalanx-distal', 'tip')),) for j in js] + \
        ['%s-finger-%s' % (f, j) for f in ('index', 'middle', 'ring', 'pinky')
         for j in ('metacarpal', 'phalanx-proximal', 'phalanx-intermediate', 'phalanx-distal', 'tip')]


def load(path):
    d = open(path, 'rb').read()
    magic, ver, ln = struct.unpack_from('<III', d, 0)
    assert magic == 0x46546C67 and ver == 2 and ln == len(d), 'not a GLB 2 file'
    off, ch = 12, []
    while off < ln:
        cl, ct = struct.unpack_from('<II', d, off)
        ch.append((ct, d[off + 8:off + 8 + cl]))
        off += 8 + cl
    assert ch[0][0] == 0x4E4F534A and ch[1][0] == 0x004E4942, 'JSON + BIN chunks'
    return d, json.loads(ch[0][1]), ch[1][1]


def accessor(j, b, i):
    a = j['accessors'][i]
    bv = j['bufferViews'][a['bufferView']]
    fmt = {5126: 'f', 5123: 'H', 5121: 'B', 5125: 'I'}[a['componentType']]
    nc = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4, 'MAT4': 16}[a['type']]
    assert 'byteStride' not in bv or bv['byteStride'] == struct.calcsize('<' + fmt * nc), 'interleaved'
    o = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
    vals = struct.unpack_from('<' + fmt * (nc * a['count']), b, o)
    return [vals[k * nc:(k + 1) * nc] for k in range(a['count'])]


def fl(v):
    s = '%.6g' % v
    return (s if ('.' in s or 'e' in s) else s + '.0') + 'f'


def main():
    args = [a for a in sys.argv[1:] if a != '--check']
    check = '--check' in sys.argv
    glb = args[0] if args else GLB
    out = args[1] if len(args) > 1 else OUT
    raw, j, b = load(glb)
    sha = hashlib.sha256(raw).hexdigest()
    assert sha == SHA, 'not the recorded right.glb (sha256 %s)' % sha
    nodes = j['nodes']
    skin = j['skins'][0]
    assert [nodes[k]['name'] for k in skin['joints']] == NAMES, 'joint order'
    mesh = j['meshes'][0]['primitives']
    assert len(mesh) == 1
    at = mesh[0]['attributes']
    P = accessor(j, b, at['POSITION'])
    N = accessor(j, b, at['NORMAL'])
    J = accessor(j, b, at['JOINTS_0'])
    W = accessor(j, b, at['WEIGHTS_0'])
    I = [t[0] for t in accessor(j, b, mesh[0]['indices'])]
    IB = accessor(j, b, skin['inverseBindMatrices'])
    rest = []
    for k in skin['joints']:
        n = nodes[k]
        q, t = n['rotation'], n['translation']
        assert max(abs(s - 1) for s in n.get('scale', [1, 1, 1])) < 1e-5, 'scaled joint'
        rest.append(list(q) + list(t))
    # the inverse bind matrices are the rest transforms' inverses (checked: model-space rest = bind)
    for k, ib in enumerate(IB):
        x, y, z, w = rest[k][:4]
        R = [[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
             [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
             [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]]
        t = rest[k][4:]
        for r in range(3):  # inverse: R^T, -R^T t; glTF matrices are column-major
            for c in range(3):
                assert abs(ib[c * 4 + r] - R[c][r]) < 2e-4, ('ibm rot', k)
            assert abs(ib[12 + r] + sum(R[c][r] * t[c] for c in range(3))) < 2e-4, ('ibm pos', k)
    for wv in W:
        assert abs(sum(wv) - 1) < 1e-4
    L = []
    L.append('/* somvr_handmesh.h - GENERATED by scripts/handmesh_gen.py from mod/somvr/assets/generic-hand/right.glb')
    L.append(' * (sha256 %s); do not edit. The VR hands\' mesh (SOMVR_XR_HANDS, docs/re-xr-pipeline.md 33).' % SHA)
    L.append(' *')
    L.append(' * The WebXR Input Profiles\' generic-hand (npm @webxr-input-profiles/assets 1.0.20), MIT License,')
    L.append(' * Copyright (c) 2019 Amazon. Permission is hereby granted, free of charge, to any person obtaining a copy of')
    L.append(' * this software and associated documentation files (the "Software"), to deal in the Software without')
    L.append(' * restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute,')
    L.append(' * sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is furnished to')
    L.append(' * do so, subject to the following conditions: The above copyright notice and this permission notice (including')
    L.append(' * the next paragraph) shall be included in all copies or substantial portions of the Software.')
    L.append(' * THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED')
    L.append(' * TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL')
    L.append(' * THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF')
    L.append(' * CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER')
    L.append(' * DEALINGS IN THE SOFTWARE.')
    L.append(' *')
    L.append(' * Model space: metres, the right hand, the fingers along -Y, the back of the hand +X, the thumb toward -Z.')
    L.append(' * Joints in the WebXR order (somvr_vrhands.h SOMVR_VHJ_*), rest = model-space pose (q x y z w, t x y z). */')
    L.append('#ifndef SOMVR_HANDMESH_H')
    L.append('#define SOMVR_HANDMESH_H')
    L.append('#include <stdint.h>')
    L.append('#define SOMVR_HM_NV %d' % len(P))
    L.append('#define SOMVR_HM_NI %d' % len(I))
    L.append('#define SOMVR_HM_NJ %d' % len(rest))
    L.append('static const float somvr_hm_rest[SOMVR_HM_NJ][7] = {')
    for k, r in enumerate(rest):
        L.append('    {%s}, /* %d %s */' % (', '.join(fl(v) for v in r), k, NAMES[k]))
    L.append('};')
    L.append('static const float somvr_hm_pos[SOMVR_HM_NV][3] = {')
    for k in range(0, len(P), 4):
        L.append('    ' + ' '.join('{%s},' % ', '.join(fl(v) for v in p) for p in P[k:k + 4]))
    L.append('};')
    L.append('static const float somvr_hm_nrm[SOMVR_HM_NV][3] = {')
    for k in range(0, len(N), 4):
        L.append('    ' + ' '.join('{%s},' % ', '.join(fl(v) for v in p) for p in N[k:k + 4]))
    L.append('};')
    L.append('static const uint8_t somvr_hm_joint[SOMVR_HM_NV][4] = {')
    for k in range(0, len(J), 8):
        L.append('    ' + ' '.join('{%s},' % ', '.join(str(v) for v in p) for p in J[k:k + 8]))
    L.append('};')
    L.append('static const float somvr_hm_weight[SOMVR_HM_NV][4] = {')
    for k in range(0, len(W), 4):
        L.append('    ' + ' '.join('{%s},' % ', '.join(fl(v) for v in p) for p in W[k:k + 4]))
    L.append('};')
    L.append('static const uint16_t somvr_hm_idx[SOMVR_HM_NI] = {')
    for k in range(0, len(I), 18):
        L.append('    ' + ' '.join('%d,' % v for v in I[k:k + 18]))
    L.append('};')
    L.append('#endif')
    text = '\n'.join(L) + '\n'
    if check:
        same = os.path.exists(out) and open(out).read() == text
        print('handmesh: %s %s' % (os.path.relpath(out), 'up to date' if same else 'DIFFERS from the generator'))
        sys.exit(0 if same else 1)
    open(out, 'w').write(text)
    print('handmesh: %s: %d vertices, %d triangles, %d joints' % (os.path.relpath(out), len(P), len(I) // 3, len(rest)))


if __name__ == '__main__':
    main()
